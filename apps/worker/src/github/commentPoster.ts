import { Octokit } from '@octokit/rest';
import { Confidence } from '@livedoc-sync/shared';

export interface CommentData {
    summary: string;
    docsChecklist: string;
    suggestedPatch: string;
    confidence: Confidence;
    truncated: boolean;
}

/**
 * Posts AI-generated analysis as a PR comment
 */
export async function postPRComment(
    octokit: Octokit,
    owner: string,
    repo: string,
    prNumber: number,
    data: CommentData
): Promise<void> {
    const { summary, docsChecklist, suggestedPatch, confidence, truncated } = data;

    const confidenceBadge = getConfidenceBadge(confidence);
    const truncationWarning = truncated
        ? '\n\n> ⚠️ **Note:** The diff was truncated due to size. Analysis may be incomplete.\n'
        : '';

    const patchSection =
        suggestedPatch.trim() !== ''
            ? `
## 📝 Suggested Documentation Patch

\`\`\`markdown
${suggestedPatch}
\`\`\`

*This is an AI-generated suggestion. Please review and adjust as needed.*
`
            : '';

    const commentBody = `
## 🤖 LiveDoc Sync - Documentation Impact Analysis

${truncationWarning}

### Summary
${summary}

### 📚 Documentation Checklist
${docsChecklist}

${patchSection}

---

${confidenceBadge} | *This comment was generated by AI. Please review carefully.*
`.trim();

    await octokit.issues.createComment({
        owner,
        repo,
        issue_number: prNumber,
        body: commentBody,
    });

    console.log(`💬 Posted comment on PR #${prNumber}`);
}

function getConfidenceBadge(confidence: Confidence): string {
    switch (confidence) {
        case 'high':
            return '🟢 **Confidence: High**';
        case 'medium':
            return '🟡 **Confidence: Medium**';
        case 'low':
            return '🔴 **Confidence: Low** - Human review recommended';
    }
}
